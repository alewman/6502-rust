//! The opcode map: which handler, addressing mode and base cycle count each
//! opcode has (`_dispatch.py`).
//!
//! `OPCODES` below is all 256 opcodes, one line each: handler, addressing
//! mode, cycles. The documented 151 are PM Appendix B's (pp. B-3 to B-29) and
//! its Appendix C timing table (p. C-1); the other 105 are NMS's opcode matrix
//! (p. 1). Both are checked opcode by opcode against the SingleStepTests
//! corpus. The table was generated from the reference's `OPCODES` dict.
//!
//! The cycle count is the base: an indexed read that crosses a page adds one
//! (`Abx`, `Aby`, `Izy`), and a taken branch adds one, or two across a
//! page. Stores and read-modify-writes spend that cycle always, so their
//! modes (`AbxW`, `AbyW`, `IzyW`) cost the same whatever the index.
//!
//! Addressing modes: `Imm` immediate, `Zp` zero page, `Zpx`/`Zpy` zero page
//! indexed, `Abs` absolute, `Abx`/`Aby` absolute indexed, `Izx` (zp,X),
//! `Izy` (zp),Y. `Implied` (the reference's `None`) means the handler makes
//! its own bus cycles: implied, accumulator, relative, the stack, JMP, JSR
//! and BRK.
//!
//! Dispatch is the table and two explicit matches: the mode's address, then
//! the handler (the reference resolves the same table into bound methods).

